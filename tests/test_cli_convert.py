from __future__ import annotations

import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from jlc2cadence import __version__
from jlc2cadence.cli import main


FIXTURE = ROOT / "tests" / "fixtures" / "demo_altium"
SLOT_FIXTURE = ROOT / "tests" / "fixtures" / "through_hole_slot"


class ConvertCliTests(unittest.TestCase):
    def test_convert_demo_outputs_assets(self) -> None:
        out_dir = Path(tempfile.mkdtemp(prefix="jlc2cadence_test_"))
        try:
            code = main(["convert", "--input", str(FIXTURE), "--models", str(FIXTURE), "--out", str(out_dir)])
            self.assertEqual(code, 0)
            expected = [
                out_dir / "reports" / "library.ir.json",
                out_dir / "reports" / "summary.json",
                out_dir / "reports" / "summary.html",
                out_dir / "reports" / "footprint_preview.svg",
                out_dir / "reports" / "symbol_preview.svg",
                out_dir / "capture" / "library.capture.xml",
                out_dir / "allegro" / "padstacks" / "padstack_specs.csv",
                out_dir / "allegro" / "symbols" / "footprints.json",
                out_dir / "allegro" / "symbols" / "symbol_build_plan.json",
                out_dir / "allegro" / "symbols" / "build_scripts" / "RES_0603.il",
                out_dir / "allegro" / "symbols" / "build_scripts" / "RES_0603.scr",
                out_dir / "scripts" / "generate_allegro.il",
                out_dir / "scripts" / "create_symbols.ps1",
                out_dir / "scripts" / "cadence_run_notes.md",
                out_dir / "3d" / "3d_model_map.json",
            ]
            for path in expected:
                self.assertTrue(path.exists(), f"missing {path}")

            data = json.loads((out_dir / "reports" / "library.ir.json").read_text(encoding="utf-8"))
            self.assertEqual(data["components"][0]["name"], "R_DEMO")
            self.assertEqual(data["footprints"][0]["model3d"]["format"], "step")
            skill = (out_dir / "scripts" / "generate_allegro.il").read_text(encoding="utf-8")
            self.assertIn('printf("jlc2cadence footprints: %d\\n" 1)', skill)
            self.assertIn("j2cCompileExistingDra", skill)
            plan = json.loads((out_dir / "allegro" / "symbols" / "symbol_build_plan.json").read_text(encoding="utf-8"))
            self.assertEqual(plan["symbols"][0]["dra"], "RES_0603.dra")
            self.assertEqual(plan["symbols"][0]["psm"], "RES_0603.psm")
            self.assertEqual(plan["symbols"][0]["status"], "script_ready")
            self.assertEqual(plan["symbols"][0]["skill_script"], "build_scripts/RES_0603.il")
            build_skill = (out_dir / "allegro" / "symbols" / "build_scripts" / "RES_0603.il").read_text(encoding="utf-8")
            self.assertIn(f"Generated by jlc2cadence v{__version__}", build_skill)
            self.assertIn("axlDBChangeDesignExtents", build_skill)
            self.assertIn('axlDBCreateText("R*"', build_skill)
            self.assertIn("axlDBCreatePadStack", build_skill)
            self.assertIn("axlPadstackToDisk", build_skill)
            self.assertIn("axlDBCreatePin", build_skill)
            self.assertIn("axlSaveDesign", build_skill)
            build_replay = (out_dir / "allegro" / "symbols" / "build_scripts" / "RES_0603.scr").read_text(encoding="utf-8")
            self.assertIn("scriptmode +invisible", build_replay)
            self.assertIn("(j2cBuildPackage_RES_0603)", build_replay)
            create_symbols = (out_dir / "scripts" / "create_symbols.ps1").read_text(encoding="utf-8")
            self.assertIn("-symbol', 'package'", create_symbols)
            self.assertIn("create_sym -p", create_symbols)
        finally:
            shutil.rmtree(out_dir, ignore_errors=True)

    def test_convert_slot_fixture_outputs_slot_padstack_assets(self) -> None:
        out_dir = Path(tempfile.mkdtemp(prefix="jlc2cadence_slot_test_"))
        try:
            code = main(["convert", "--input", str(SLOT_FIXTURE), "--models", str(SLOT_FIXTURE), "--out", str(out_dir)])
            self.assertEqual(code, 0)
            ir = json.loads((out_dir / "reports" / "library.ir.json").read_text(encoding="utf-8"))
            pads = ir["footprints"][0]["pads"]
            self.assertEqual(pads[0]["kind"], "thru_hole")
            self.assertEqual(pads[0]["hole_diameter"], 0.8)
            self.assertEqual(pads[1]["slot_size"], [0.8, 1.8])
            self.assertEqual(pads[1]["properties"]["plated"], "false")

            padstack_specs = (out_dir / "allegro" / "padstacks" / "padstack_specs.csv").read_text(encoding="utf-8")
            self.assertIn("slot_x_mm", padstack_specs)
            self.assertIn("0.8,1.8,false", padstack_specs)

            build_skill = (out_dir / "allegro" / "symbols" / "build_scripts" / "CONN_SLOT.il").read_text(
                encoding="utf-8"
            )
            self.assertIn("?holeType 'CIRCLE_DRILL", build_skill)
            self.assertIn("?holeType 'OVAL_SLOT", build_skill)
            self.assertIn("?slotSize 0.8:1.8", build_skill)
            self.assertIn("?plating 'NON_PLATED", build_skill)
        finally:
            shutil.rmtree(out_dir, ignore_errors=True)


if __name__ == "__main__":
    unittest.main()
